/**
 * Окно после открытия модалки, в течение которого её нельзя закрыть тапом.
 *
 * Зачем: модалка полного названия открывается по долгому нажатию (450 мс).
 * Палец в этот момент ещё на экране, и его отпускание рождает обычный `click`
 * уже по подложке модалки — она закрывалась сразу после открытия, и казалось,
 * что «долгий тап перестал показывать название». Тот же тап не должен
 * считаться осознанным «закрыть».
 */
export const TAP_CLOSE_GUARD_MS = 350;

/** true — тап пришёл слишком скоро после открытия, закрывать нельзя. */
export function isPhantomTap(
  openedAt: number,
  now: number,
  guardMs: number = TAP_CLOSE_GUARD_MS,
): boolean {
  if (!openedAt) return false;
  return now - openedAt < guardMs;
}
