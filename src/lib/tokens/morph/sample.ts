import {
  ADJ_SLOTS,
  MORPH_CASES,
  MORPH_FORMAT,
  MORPH_VERSION,
  NOUN_SLOTS,
  type MorphDictionary,
  type MorphLemmaEntry,
} from "./format";

/** Собрать запись существительного из 12 форм. */
export function noun(gender: "m" | "f" | "n" | "", ...forms: (string | null)[]): MorphLemmaEntry {
  if (forms.length !== NOUN_SLOTS) throw new Error(`нужно ${NOUN_SLOTS} форм`);
  return { p: "N", ...(gender ? { g: gender } : {}), f: forms };
}

/** Собрать запись прилагательного из 24 форм. */
export function adjective(...forms: (string | null)[]): MorphLemmaEntry {
  if (forms.length !== ADJ_SLOTS) throw new Error(`нужно ${ADJ_SLOTS} форм`);
  return { p: "A", f: forms };
}

