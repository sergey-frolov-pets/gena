/**
 * Защищённый режим: у открытого диалога он хранится флагом в записи,
 * а на экране «Новый диалог» записи ещё нет.
 *
 * Поэтому у экрана без сессии работает «намерение»: кнопка режима переключается
 * сразу, справочник доступен, выделение в поле ввода даёт плашку, а флаг
 * переносится в запись в момент её создания. Иначе режим в новом диалоге
 * выглядел бы недоступным, хотя технически всё уже готово.
 */

export interface TokenModeSession {
  tokenMode?: boolean;
}

/**
 * Включён ли защищённый режим: флаг диалога, а для ещё не созданного диалога —
 * намерение, выставленное кнопкой.
 */
export function tokenModeActive(
  session: TokenModeSession | null | undefined,
  pending: boolean,
): boolean {
  return session ? session.tokenMode === true : pending;
}

/**
 * Снять защиту можно, пока в этом диалоге нет ни одной связи
 * «значение — токен». Записи справочника сами по себе не держат режим:
 * они могли появиться в другом диалоге.
 */
export function tokenModeCanTurnOff(linkedNames: readonly string[]): boolean {
  return linkedNames.length === 0;
}
