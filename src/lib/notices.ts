/**
 * Служебные плашки сервера внутри хода.
 *
 * PicoClaw при сбое модели публикует в чат обычное сообщение без `kind`,
 * например «⏳ Модель не ответила вовремя. Повтори сообщение — я переключусь
 * на резервную модель.» (см. `pkg/agent/error_format.go`). Ход при этом часто
 * продолжается: включается fallback-модель и в чат идут размышления.
 *
 * Клиент не должен принимать такую плашку за финальный ответ: иначе в истории
 * появляется «ошибка» вместо ответа, а ход обрывается на середине.
 *
 * Здесь только чистая классификация текста — решения принимает транспорт.
 */

/** Маркеры, с которых начинаются служебные сообщения PicoClaw. */
const NOTICE_PREFIXES = ["⏳", "⚠️", "⚠", "🔑"];

/** Характерные куски текста (в нижнем регистре). */
const NOTICE_HINTS = [
  "не ответила вовремя",
  "не ответил вовремя",
  "переключусь на резервную модель",
  "перегружена (лимит запросов)",
  "закончилась бесплатная квота",
  "не смог обработать сообщение",
  "технические детали записал",
  "ключ api не принят",
  "для этой модели не задан ключ",
  "токен входа истёк",
  "ошибка авторизации",
  "context window exceeded",
  "compressing history",
  "did not respond in time",
  "rate limit exceeded",
  "quota exceeded",
];

/** Служебная плашка короткая: длинный текст — это уже ответ. */
const MAX_NOTICE_CHARS = 400;
/** Больше трёх строк — точно не плашка. */
const MAX_NOTICE_LINES = 3;

/**
 * Похоже ли сообщение на служебную плашку сервера, а не на ответ агента.
 *
 * Осознанно консервативно: лучше принять плашку за ответ, чем спрятать
 * настоящий ответ, который случайно начинается с эмодзи.
 */
export function isTurnNotice(text: string): boolean {
  const value = text.trim();
  if (!value) return false;
  if (value.length > MAX_NOTICE_CHARS) return false;
  if (value.split("\n").length > MAX_NOTICE_LINES) return false;

  if (NOTICE_PREFIXES.some((prefix) => value.startsWith(prefix))) return true;

  const lower = value.toLowerCase();
  return NOTICE_HINTS.some((hint) => lower.includes(hint));
}
